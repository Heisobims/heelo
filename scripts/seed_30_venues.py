async def seed_venues():
    async with AsyncSessionLocal() as db:
        print(f"Beginning seed of {len(VENUES_DATA)} international venues...")

        # 1. Fetch admin user to assign reviews and default ownership
        admin = await db.scalar(select(User).where(User.email == "admin@tixdoo.com"))
        if not admin:
            admin = await db.scalar(select(User).limit(1))
            if not admin:
                print("No user found in database. Aborting.")
                return

        for vd in VENUES_DATA:
            existing_v = await db.scalar(select(Vendor).where(Vendor.slug == vd["slug"]))
            if existing_v:
                print(f"Venue {vd['slug']} already exists, skipping.")
                continue

            # Ensure vendor user exists
            v_user = await db.scalar(select(User).where(User.email == vd["email"]))
            if not v_user:
                v_user = User(
                    email=vd["email"],
                    full_name=vd["name"] + " Concierge",
                    password_hash=hash_password("VenueWorldPass2026!"),
                    role="vendor",
                    is_verified=True,
                )
                db.add(v_user)
                await db.flush()

            # Create Vendor with category='venue' and capacity set
            v_obj = Vendor(
                user_id=v_user.id,
                business_name=vd["name"],
                slug=vd["slug"],
                category="venue",
                tagline=vd["tagline"],
                description=vd["description"],
                location_city=vd["city"],
                location_country=vd["country"],
                address=vd["address"],
                capacity=vd["capacity"],
                contact_email=vd["email"],
                contact_phone=vd["phone"],
                website_url=f"https://{vd['slug']}.com",
                cover_image_url=vd["cover_url"],
                logo_url=vd["logo_url"],
                portfolio_urls=vd["portfolio"],
                service_areas=vd["service_areas"],
                social_links={
                    "instagram": f"https://instagram.com/{vd['slug']}",
                    "website": f"https://{vd['slug']}.com",
                },
                operating_hours={
                    "monday": "08:00 - 23:00",
                    "tuesday": "08:00 - 23:00",
                    "wednesday": "08:00 - 23:00",
                    "thursday": "08:00 - 23:00",
                    "friday": "08:00 - 02:00",
                    "saturday": "08:00 - 02:00",
                    "sunday": "09:00 - 22:00",
                },
                faqs=[
                    {
                        "question": "What is the maximum guest capacity and layout flexibility?",
                        "answer": f"{vd['name']} can accommodate up to {vd['capacity']:,} guests for standing receptions, with modular configurations for banquet dining, theater-style keynotes, and classroom breakouts.",
                    },
                    {
                        "question": "Do you permit outside catering and external beverage vendors?",
                        "answer": "We maintain a list of certified five-star catering partners and also permit approved external caterers with valid licenses and kitchen prep buy-in agreements.",
                    },
                    {
                        "question": "What audio/visual and technical staging infrastructure is included?",
                        "answer": "Our spaces are equipped with professional sound reinforcement, high-gain projectors or LED displays, dedicated DMX lighting rigs, and dedicated gigabit WiFi for attendees and production crews.",
                    },
                ],
                starting_price=vd["starting_price"],
                currency=vd["currency"],
                price_range=vd["price_range"],
                status="active",
                is_verified=True,
                verification_status="verified",
                verified_at=datetime.now(timezone.utc) - timedelta(days=90),
                subscription_tier="premium",
                rating_avg=vd["rating"],
                reviews_count=vd["reviews_count"],
                is_featured=True,
            )
            db.add(v_obj)
            await db.flush()

            # Add Service Listings
            for s in vd["services"]:
                s_obj = VendorServiceListing(
                    vendor_id=v_obj.id,
                    title=s["title"],
                    slug=s["slug"],
                    category="venue",
                    description=f"Exclusive venue package: {s['title']} at {vd['name']}.",
                    pricing_type="starting_at",
                    price=s["price"],
                    currency=vd["currency"],
                    inclusions=s["inclusions"],
                    duration_hours=s["duration_hours"],
                    is_active=True,
                )
                db.add(s_obj)

            # Add Reviews
            for r in vd["reviews"]:
                r_obj = VendorReview(
                    vendor_id=v_obj.id,
                    reviewer_id=admin.id,
                    rating=r["rating"],
                    title=r["title"],
                    content=r["content"],
                    status="published",
                )
                db.add(r_obj)

            print(f"Created venue: {v_obj.business_name} | {vd['city']}, {vd['country']} | Capacity: {vd['capacity']}")

        await db.commit()
        print("Successfully created all 30 venues with complete setup!")

